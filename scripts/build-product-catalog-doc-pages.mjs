#!/usr/bin/env node
/**
 * Convert Product Catalog PDF docs → PNG page images for the in-app viewer.
 *
 * Source:  app-slab-inventory/public/product-catalog/docs/<id>/<id>.pdf
 * Output:  app-slab-inventory/public/product-catalog/doc-pages/<id>/page-N.png
 * Manifest: app-slab-inventory/src/lib/productCatalogDocPages.generated.ts
 *
 * Uses PyMuPDF (pymupdf) via Python — no iframe/PDF embed needed in the UI.
 *
 * Usage:
 *   node scripts/build-product-catalog-doc-pages.mjs
 *   node scripts/build-product-catalog-doc-pages.mjs --only blanco-blanco-diamond-50-50-regular-divide
 */
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "..");
const docsRoot = path.join(repoRoot, "app-slab-inventory/public/product-catalog/docs");
const pagesRoot = path.join(repoRoot, "app-slab-inventory/public/product-catalog/doc-pages");
const manifestPath = path.join(
  repoRoot,
  "app-slab-inventory/src/lib/productCatalogDocPages.generated.ts"
);

const onlyArg = process.argv.includes("--only")
  ? process.argv[process.argv.indexOf("--only") + 1]
  : null;

const ZOOM = 2.0; // ~144 dpi equivalent

const pythonScript = `
import json, sys
from pathlib import Path
try:
    import fitz
except ImportError:
    print("ERROR: pymupdf is required. Install with: python3 -m pip install --user pymupdf", file=sys.stderr)
    sys.exit(2)

docs_root = Path(sys.argv[1])
pages_root = Path(sys.argv[2])
zoom = float(sys.argv[3])
only = sys.argv[4] if len(sys.argv) > 4 and sys.argv[4] else None

results = {}
pdfs = sorted(docs_root.glob("*/*.pdf"))
if only:
    pdfs = [p for p in pdfs if p.parent.name == only]
if not pdfs:
    print(json.dumps({"ok": False, "error": "no pdfs found", "results": {}}))
    sys.exit(1)

mat = fitz.Matrix(zoom, zoom)
for pdf in pdfs:
    product_id = pdf.parent.name
    out_dir = pages_root / product_id
    out_dir.mkdir(parents=True, exist_ok=True)
    # Remove stale pages so page counts stay accurate
    for stale in out_dir.glob("page-*.png"):
        stale.unlink()
    doc = fitz.open(pdf)
    urls = []
    for i, page in enumerate(doc, start=1):
        pix = page.get_pixmap(matrix=mat, alpha=False)
        dest = out_dir / f"page-{i}.png"
        pix.save(dest)
        urls.append(f"/product-catalog/doc-pages/{product_id}/page-{i}.png")
    doc.close()
    results[product_id] = {
        "pageCount": len(urls),
        "pageImageUrls": urls,
        "pdfUrl": f"/product-catalog/docs/{product_id}/{product_id}.pdf",
    }
    print(f"OK {product_id} ({len(urls)} page(s))", file=sys.stderr)

print(json.dumps({"ok": True, "results": results}))
`;

function main() {
  if (!fs.existsSync(docsRoot)) {
    console.error(`Docs root missing: ${docsRoot}`);
    process.exit(1);
  }
  fs.mkdirSync(pagesRoot, { recursive: true });

  const pyArgs = [docsRoot, pagesRoot, String(ZOOM)];
  if (onlyArg) pyArgs.push(onlyArg);

  const run = spawnSync("python3", ["-c", pythonScript, ...pyArgs], {
    encoding: "utf8",
    maxBuffer: 32 * 1024 * 1024,
  });

  if (run.status !== 0) {
    process.stderr.write(run.stderr || run.stdout || "python conversion failed\n");
    process.exit(run.status || 1);
  }
  if (run.stderr) process.stderr.write(run.stderr);

  const lines = (run.stdout || "").trim().split("\n").filter(Boolean);
  const payloadLine = lines[lines.length - 1];
  let payload;
  try {
    payload = JSON.parse(payloadLine);
  } catch (err) {
    console.error("Failed to parse conversion JSON:", err);
    console.error(run.stdout);
    process.exit(1);
  }
  if (!payload.ok) {
    console.error(payload.error || "conversion failed");
    process.exit(1);
  }

  const entries = Object.entries(payload.results).sort(([a], [b]) => a.localeCompare(b));
  const body = entries
    .map(([id, meta]) => {
      const urls = meta.pageImageUrls.map((u) => `    ${JSON.stringify(u)}`).join(",\n");
      return `  ${JSON.stringify(id)}: [\n${urls}\n  ]`;
    })
    .join(",\n");

  const file = `/**
 * AUTO-GENERATED by scripts/build-product-catalog-doc-pages.mjs
 * Do not edit by hand — re-run the script after adding/updating PDFs.
 */
export const PRODUCT_CATALOG_DOC_PAGES: Readonly<Record<string, readonly string[]>> = {
${body}
};
`;

  fs.writeFileSync(manifestPath, file, "utf8");
  console.log(`Wrote ${entries.length} doc page sets → ${path.relative(repoRoot, pagesRoot)}`);
  console.log(`Manifest → ${path.relative(repoRoot, manifestPath)}`);
}

main();
